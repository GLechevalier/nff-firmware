// babynffRepo — a bundled, frontend-only "connected repo" for the first-login demo project.
//
// A brand-new user lands on the "Welcome to nff" demo project (projects.is_demo) with a live mock
// fleet but no GitHub repo, so the Code/GitHub tabs are dead ends. The whole nff story is "a change
// ships → a device crash-loops → the agent edits the source → OTA heals it", but there's no source
// to look at. This module ships the ACTUAL firmware the demo's L2 (QEMU ESP32) devices run, as a
// static asset, so it can be browsed the moment you log in.
//
// `main/main.c` is HEALTHY at rest. It turns into the buggy twin only once the break demo has armed
// a fault (see babynffRepoTree/babynffRepoFile below) — the user is meant to watch the bug arrive,
// not find it waiting for them.
//
// It's injected as a virtual github_connections row (useGithubConnections, gated to is_demo + no real
// repo) and served locally by useRepoTree/fetchRepoFile (the nff-github proxy can't clone a repo that
// has no GitHub App installation). It disappears the instant a real repo is connected. There is no
// backend, migration, or DB row behind it.

import type { RepoTreeEntry } from '../hooks/useRepoTree';
import type { GithubConnection } from '../add-ons/github/types/github';
import {
  BABYNFF_CREDENTIALS_PATH,
  BABYNFF_MAIN_C_BUGGY,
  BABYNFF_MAIN_C_CLEAN,
  BABYNFF_MAIN_PATH,
} from './babynffFirmware';

export const BABYNFF_REPO = 'babynff/babynff-repo';
export const BABYNFF_BRANCH = 'main';

// Stable fake tree shas. useRepoTree hands the sha to fetchRepoFile as the `ref`, and CodeTab keys
// its per-file cache on it — so flipping the sha when the demo breaks is what makes the tab drop the
// clean firmware and re-read the buggy one. Two constants, no cache-busting nonce needed.
export const BABYNFF_SHA_CLEAN = 'babynff-demo';
export const BABYNFF_SHA_BROKEN = 'babynff-demo-broken';

const README = `# babynff-repo

The firmware running on your demo fleet's ESP32 devices. Right now, it's healthy.

The two \`nff-qemu-esp32\` ("L2") devices in your fleet are real \`qemu-system-xtensa\` emulators
booting the firmware in [\`main/main.c\`](main/main.c): an SOS-in-Morse blink driven from a dedicated
FreeRTOS task, so the nff task — MQTT, heartbeat, signed commands, OTA, pinned to the other core — is
never starved.

## This is real ESP32 code

\`main/main.c\` is an ordinary ESP-IDF application. \`app_main()\`, an \`esp_wifi\` station bring-up,
\`#include "nff.h"\`, the \`credentials.h\` that \`nff provision new-device\` generated, and the nff SDK
on its own task. \`idf.py build\` puts it on a real ESP32 unchanged — nothing here is demo scaffolding.

QEMU emulates no WiFi radio, only an Ethernet MAC, and one image serves every mock device. So the
L2 build force-includes a shim that maps the \`esp_wifi\` station bring-up onto the emulated MAC and
reads this device's identity from its NVS partition instead of the \`credentials.h\` baked in above.
**The source is untouched either way** — what you read here is what you can flash.

## Break it, and watch it heal

Press **Break a device**. nff merges a commit to this repo — a plausible little feature, reading an
I2C temperature sensor — whose author forgot that the read fails while the bus is busy. It ships to
the fleet over OTA. Then:

1. **GitHub** — the commit lands, deploys, and rolls out. Nothing looks wrong yet.
2. **Dashboard** — a device dot goes amber → red as the L2 crash-loops on the bug.
3. **Crash** — nff pulls the ESP32 coredump and resolves the backtrace (via \`addr2line\` against the
   real ELF) to the exact faulting line.
4. **Code** — the agent opens \`main/main.c\`, adds the missing null guard, and opens a fix PR.
5. **OTA** — the new image rolls out; the device reboots clean and the dot goes green.

The bug it ships is one missing line. \`read_sensor()\` returns \`NULL\` while the I2C bus is busy:

\`\`\`c
Reading *r = read_sensor();
ESP_LOGI(TAG, "temp=%d C", r->celsius);   // BUG(null_deref): r may be NULL — no guard
\`\`\`

and the fix guards the dereference before using \`r\`:

\`\`\`c
Reading *r = read_sensor();
if (r == NULL) return;                    // bus busy this cycle — skip
ESP_LOGI(TAG, "temp=%d C", r->celsius);
\`\`\`

That's the change nff makes for you, automatically, and ships over OTA.

## Layout

- \`main/main.c\` — the device firmware (ESP-IDF app, compiled to a real ESP32 image)
- \`main/credentials.h\` — per-device identity + certs, generated by \`nff provision new-device\`
- \`CMakeLists.txt\` / \`main/CMakeLists.txt\` — the ESP-IDF build (component registration, board target)
- \`sdkconfig.defaults\` — build config (target, custom partition table, coredump to flash)
- \`partitions.csv\` — flash layout: two OTA app slots so an OTA flip + rollback can be exercised

> This is a demo repo bundled into the dashboard. Connect your own GitHub repo (GitHub tab →
> **Connect**) to replace it with your real firmware — this one vanishes as soon as you do.
`;

