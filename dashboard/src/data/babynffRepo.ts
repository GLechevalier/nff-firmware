// Browse order: README, the top project file, the firmware, then the supporting files.
const TREE_ORDER = [
  'README.md',
  'CMakeLists.txt',
  BABYNFF_MAIN_PATH,
  'main/CMakeLists.txt',
  BABYNFF_CREDENTIALS_PATH,
  'sdkconfig.defaults',
  'partitions.csv',
];

/**
 * The mock repo's file tree, in the shape useRepoTree returns.
 *
 * `broken` picks the tree sha, not the file list — the paths never change, only what `main/main.c`
 * contains. Callers hand that sha back to babynffRepoFile as the `ref`, so the two can't disagree,
 * and CodeTab's per-file cache (keyed on repo@sha:path) drops the stale firmware for free.
 */
export function babynffRepoTree(broken: boolean): { entries: RepoTreeEntry[]; sha: string } {
  return {
    entries: TREE_ORDER.map(path => ({ path, type: 'blob' as const })),
    sha: broken ? BABYNFF_SHA_BROKEN : BABYNFF_SHA_CLEAN,
  };
}

/**
 * Bundled content for a path (null when the path isn't part of the mock repo).
 *
 * `ref` is the tree sha from babynffRepoTree. Only `main/main.c` reads it: the demo serves the
 * healthy firmware at rest and the buggy twin once the break has armed a fault. Anything else — an
 * unknown ref, a missing path — falls back to the healthy firmware, because a demo that shows a bug
 * it can't explain is worse than one that shows none.
 */
export function babynffRepoFile(path: string, ref?: string | null): string | null {
  if (path === BABYNFF_MAIN_PATH) {
    return ref === BABYNFF_SHA_BROKEN ? BABYNFF_MAIN_C_BUGGY : BABYNFF_MAIN_C_CLEAN;
  }
  return FILES[path] ?? null;
}

/** A synthetic connection so the mock repo appears in the GitHub + Code tabs. */
export function babynffConnection(projectId: string): GithubConnection {
  return {
    id: `babynff-virtual:${projectId}`,
    repoFullName: BABYNFF_REPO,
    installationId: null,
    productionBranch: BABYNFF_BRANCH,
    // No real device_group behind this; the GitHub tab falls back to showing this string (sliced to
    // 8 chars) as the group name, so keep it short + readable ("main → L2 QEMU").
    deviceGroupId: 'L2 QEMU',
    deviceTypes: ['nff-qemu-esp32'],
    deployPolicy: 'auto',
    createdAt: new Date('2026-01-01T00:00:00Z'),
    virtual: true,
  };
}
